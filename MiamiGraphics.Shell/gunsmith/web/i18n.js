  const SLAVIC = { ru: 1, pl: 1 };
  function pluralForm(lang, n) {
    const v = Math.abs(Number(n));
    if (!isFinite(v)) return SLAVIC[lang] ? 'many' : 'other';
    if (SLAVIC[lang]) {
      if (!Number.isInteger(v)) return 'many';
      const m10 = v % 10, m100 = v % 100;
      if (lang === 'pl') {
        if (v === 1) return 'one';
        if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'few';
        return 'many';
      }
      if (m10 === 1 && m100 !== 11) return 'one';
      if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'few';
      return 'many';
    }
    return v === 1 ? 'one' : 'other';
  }

  function normalize(v) {
    const s = String(v || '').trim().toLowerCase().slice(0, 2);
    return DICT[s] ? s : '';
  }
  let LANG = normalize(new URLSearchParams(location.search).get('lang')) || FALLBACK;

  const listeners = [];

  function interpolate(s, params) {
    if (!params) return s;
    return s.replace(/\{\{\s*(\w+)\s*\}\}/g, (m, k) =>
      (params[k] === undefined || params[k] === null) ? '' : String(params[k]));
  }

  function lookup(dict, lang, key, params) {
    if (!dict) return null;
    if (params && params.count !== undefined && params.count !== null) {
      const forms = [key + '_' + pluralForm(lang, params.count), key + '_other', key + '_many', key];
      for (const k of forms) if (typeof dict[k] === 'string') return dict[k];
      return null;
    }
    return typeof dict[key] === 'string' ? dict[key] : null;
  }

  function t(key, params) {
    let s = lookup(DICT[LANG], LANG, key, params);
    if (s === null) s = lookup(DICT[FALLBACK], FALLBACK, key, params);
    if (s === null) s = key;
    return interpolate(s, params);
  }

  function textNodes(el) {
    const out = [];
    for (const n of el.childNodes) if (n.nodeType === 3) out.push(n);
    return out;
  }
  function setNode(node, str, store, slot) {
    if (!store[slot]) {
      const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(node.nodeValue || '');
      store[slot] = [m ? m[1] : '', m ? m[3] : ''];
    }
    node.nodeValue = store[slot][0] + str + store[slot][1];
  }
  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-tail]').forEach(el => {
      const ns = textNodes(el); if (!ns.length) return;
      el.__i18nPad = el.__i18nPad || {};
      setNode(ns[ns.length - 1], t(el.getAttribute('data-i18n-tail')), el.__i18nPad, 'tail');
    });
    scope.querySelectorAll('[data-i18n-head]').forEach(el => {
      const ns = textNodes(el); if (!ns.length) return;
      el.__i18nPad = el.__i18nPad || {};
      setNode(ns[0], t(el.getAttribute('data-i18n-head')), el.__i18nPad, 'head');
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => el.setAttribute('title', t(el.getAttribute('data-i18n-title'))));
    scope.querySelectorAll('[data-i18n-ph]').forEach(el => el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))));
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))));
    if (!root) {
      document.title = t('app.title');
      document.documentElement.setAttribute('lang', LANG);
    }
  }

  function setLang(lang) {
    const L = normalize(lang);
    if (!L || L === LANG) return false;
    LANG = L;
    applyStatic();
    for (const fn of listeners) { try { fn(L); } catch (e) { console.warn('[i18n] listener failed', e); } }
    return true;
  }

  const getLang = () => LANG;
  function onChange(fn) { if (typeof fn === 'function') listeners.push(fn); }

  window.HGI18N = { t, setLang, getLang, onChange, applyStatic, pluralForm, langs: Object.keys(DICT) };
  window.HG_T = t;
  window.HG_SETLANG = setLang;
  window.t = t;
  window.setLang = setLang;

  applyStatic();
